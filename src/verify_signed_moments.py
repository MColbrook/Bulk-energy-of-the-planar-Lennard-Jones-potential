"""Verify signed moments and exclusion from the original Gaussian polytope.

The input is the 20-coordinate reference regenerated by
reference_coefficients.py. The calculation distinguishes the signed
Lennard--Jones data from the parameter polytope of the Gaussian certificate.
The sign inequalities are checked separately by verify_signs.py.
"""
if not __debug__:
    raise RuntimeError("Certificate checks require assertions; do not use -O or -OO.")
import argparse
import hashlib
import json
from pathlib import Path
from flint import arb, ctx

ctx.prec = 160
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--reference", required=True, type=Path)
parser.add_argument("--output", required=True, type=Path)
args = parser.parse_args()
data = json.loads(args.reference.read_text())
A, B = arb(data["A"]), arb(data["B"])
pi = arb.pi()
b, h = arb(3).sqrt() / 2, arb(17) / 50
lam, pp, kappa = pi / b, pi * h, pi / 36
residues = [0, 1, 3, 4, 7, 9, 12, 13, 16, 19, 21, 25, 27, 28, 31]
Q1 = 4 * kappa**2
for residue in residues:
    if residue != 1:
        Q1 *= (2 * (kappa * (1 - residue)).sin())**2


def moment(m, lower=arb(1), rate=None):
    """Integral_lower^infinity alpha^m exp(-rate*alpha) d alpha."""
    if rate is None:
        rate = lam
    return (rate * lower).gamma_upper(m + 1) / rate**(m + 1)


def plus_mass(lower):
    return pp.exp() / Q1 * (
        A * (lam * moment(6, lower) - pp * moment(5, lower))
        - B * (lam * moment(3, lower) - pp * moment(2, lower)))


def minus_mass(lower):
    return pp.exp() / Q1 * (
        A * (lam * moment(-5, lower) - pp * moment(-6, lower))
        - B * (lam * moment(-2, lower) - pp * moment(-3, lower)))


alpha0 = (B / A)**(arb(1) / 3)
assert A > 0 and B > A and alpha0 > 1
Iplus, Iminus = plus_mass(arb(1)), minus_mass(arb(1))
positive = plus_mass(alpha0)
negative = positive - Iplus
J = positive + negative - Iminus
assert J < arb(".425")
print("alpha_zero:", alpha0)
print("Iplus:", Iplus)
print("Iminus:", Iminus)
print("positive_plus_mass:", positive)
print("negative_plus_mass:", negative)
print("absolute_mixture_mass J:", J)
print("inherited_finite_error:", J / 10**5)
print("inherited_tail_error:", 3 * J / 10**9)


def integrated_pair(n):
    """Integrals w+/D times (z,1)*exp(-(n-1)/z)."""
    def M(m):
        return moment(m, rate=n * lam)
    common = (n * pp).exp() / Q1
    zpart = common * (A * M(5) - B * M(2))
    plain = common * (
        A * (lam * M(6) - pp * M(5))
        - B * (lam * M(3) - pp * M(2)))
    return zpart, plain


assert Iplus > 0
pairs = []
for n in [1, 3, 4, 7]:
    weighted, plain = integrated_pair(n)
    print(f"node {n}, integrated z/exponential pair:", weighted, plain)
    print(f"node {n}, normalized pair:", weighted / Iplus, plain / Iplus)
    pairs.append({"node": n, "weighted_z": str(weighted), "weighted_exponential": str(plain),
                  "normalized_z": str(weighted / Iplus),
                  "normalized_exponential": str(plain / Iplus)})
    if n > 1:
        assert plain < 0
print("PASS: normalized signed target lies outside original polytope E.")

result = {
    "scope": "Signed moments and exclusion from the original parameter polytope",
    "finite_checks_passed": True,
    "input_sha256": hashlib.sha256(args.reference.read_bytes()).hexdigest(),
    "alpha_zero": str(alpha0), "Iplus": str(Iplus), "Iminus": str(Iminus),
    "positive_plus_mass": str(positive), "negative_plus_mass": str(negative),
    "absolute_mixture_mass": str(J),
    "inherited_finite_error": str(J / 10**5),
    "inherited_tail_error": str(3 * J / 10**9),
    "integrated_pairs": pairs,
}
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(json.dumps(result, indent=2) + "\n")
